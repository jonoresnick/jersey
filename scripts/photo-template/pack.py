"""Step 3: pack the cleaned photo and maps into js/photo-assets.js. Run from this folder."""
import base64, cv2
sh = cv2.imread('out/shade.png'); lab = cv2.imread('out/labels.png', 0)
maps = sh.copy(); maps[:, :, 0] = lab * 20                     # BGR: B = label x 20, G = sheen, R = shading
cv2.imwrite('out/maps.png', maps, [cv2.IMWRITE_PNG_COMPRESSION, 9])
cv2.imwrite('out/edge_pack.png', cv2.imread('out/edge.png'), [cv2.IMWRITE_PNG_COMPRESSION, 9])
enc = lambda p: base64.b64encode(open(p, 'rb').read()).decode()
h, w = lab.shape
open('../../js/photo-assets.js', 'w').write(
    "/* Photo mock-up template (generated by scripts/photo-template — do not edit by hand).\n"
    "   base: the mannequin photo. maps: R = shading, G = sheen, B = part label x 20.\n"
    "   edge: R = soft-edge coverage, G = 255 where two parts meet. */\n"
    f"window.UB = window.UB || {{}};\nUB.PHOTO_ASSETS = {{ width: {w}, height: {h},\n"
    f"  base: 'data:image/jpeg;base64,{enc('out/clean.jpg')}',\n"
    f"  maps: 'data:image/png;base64,{enc('out/maps.png')}',\n"
    f"  edge: 'data:image/png;base64,{enc('out/edge_pack.png')}' }};\n")
print('wrote js/photo-assets.js')
