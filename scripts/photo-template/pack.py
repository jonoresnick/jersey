"""Step 3: pack the photo and maps into js/photo-assets.js. Run from this folder."""
import base64, cv2
sh = cv2.imread('out/shade.png'); lab = cv2.imread('out/labels.png', 0)
maps = sh.copy(); maps[:, :, 0] = lab * 20
cv2.imwrite('out/maps.png', maps, [cv2.IMWRITE_PNG_COMPRESSION, 9])
cv2.imwrite('out/base.jpg', cv2.imread('base.jpg'), [cv2.IMWRITE_JPEG_QUALITY, 90])
b = base64.b64encode(open('out/base.jpg', 'rb').read()).decode()
m = base64.b64encode(open('out/maps.png', 'rb').read()).decode()
h, w = lab.shape
open('../../js/photo-assets.js', 'w').write(
    "/* Photo mock-up template (generated by scripts/photo-template — do not edit by hand).\n"
    "   base: the mannequin photo. maps: R = shading, G = sheen, B = part label x 20. */\n"
    f"window.UB = window.UB || {{}};\nUB.PHOTO_ASSETS = {{ width: {w}, height: {h},\n  base: 'data:image/jpeg;base64,{b}',\n  maps: 'data:image/png;base64,{m}' }};\n")
print('wrote js/photo-assets.js')
