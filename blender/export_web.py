"""Export a Blender hockey player for the website's 3D view.

  BLEND=path/to/player.blend OUT=js/model-assets.js python blender/export_web.py

Converts text (numbers) and curves (stitching) to meshes, swaps fonts that only
exist on one computer for Blender's built-in font, lightens subdivision, drops the
studio (backdrop, lights, cameras) and writes a .glb plus a .js file that embeds it.
Object and material names are kept: the website uses them to know which part is which.
"""
import base64, os, bpy

bpy.ops.wm.open_mainfile(filepath=os.environ['BLEND'], load_ui=False, use_scripts=False)
LV = int(os.environ.get("LV", "0"))
builtin = bpy.data.fonts.load('<builtin>')
for o in bpy.data.objects:
    if o.type == 'FONT':
        o.data.font = builtin
    for m in getattr(o, 'modifiers', []):
        if m.type == 'SUBSURF':
            m.levels = min(m.levels, LV); m.render_levels = min(m.render_levels, LV)
keep = []
for o in list(bpy.data.objects):
    if o.type in ('LIGHT', 'CAMERA', 'EMPTY') or o.name in ('Backdrop', 'Floor'):
        continue
    if o.type in ('FONT', 'CURVE'):
        bpy.ops.object.select_all(action='DESELECT')
        bpy.context.view_layer.objects.active = o
        o.select_set(True)
        bpy.ops.object.convert(target='MESH')
        o = bpy.context.view_layer.objects.active
    if o.type == 'MESH':
        keep.append(o)
bpy.ops.object.select_all(action='DESELECT')
for o in keep:
    o.select_set(True)
glb = os.path.splitext(os.environ['OUT'])[0] + '.glb'
bpy.ops.export_scene.gltf(filepath=glb, export_format='GLB', use_selection=True, export_apply=True, export_yup=True,
                          export_draco_mesh_compression_enable=False)
data = base64.b64encode(open(glb, 'rb').read()).decode()
open(os.environ['OUT'], 'w').write(
    '/* 3D player for the website (generated by blender/export_web.py, do not edit by hand). */\n'
    'window.UB = window.UB || {};\n'
    f"UB.MODEL_GLB = 'data:model/gltf-binary;base64,{data}';\n")
print('PARTS', len(keep), 'GLB KB', os.path.getsize(glb) // 1024)
